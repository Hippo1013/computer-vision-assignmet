"""Reproducible CIFAR-100 stage-1 suite. Run from any working directory."""
import argparse
import hashlib
import importlib.util
import json
import platform
import random
import subprocess
import time
from pathlib import Path

import numpy as np
import torch
import torchvision
from torch import nn
from torch.utils.data import DataLoader, Subset
from torchvision import transforms

BASE = Path(__file__).resolve().parent


def write_json(path, value):
    path = Path(path)
    tmp = path.with_suffix(path.suffix + '.tmp')
    tmp.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding='utf-8')
    tmp.replace(path)


def sha(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for block in iter(lambda: f.read(1024 * 1024), b''):
            h.update(block)
    return h.hexdigest()


def seed_all(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)


def seed_worker(worker):
    seed = torch.initial_seed() % 2**32
    np.random.seed(seed)
    random.seed(seed)


def model_new(device):
    spec = importlib.util.spec_from_file_location('course_model', BASE / 'cv_homework2/resnet-cifar100.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module.resnet10(num_classes=100).to(device)


def lr_at(config, epoch):
    return config['lr'] * (0.1 ** sum(epoch > m for m in config.get('milestones', [])))


def optimizer_new(model, config):
    if config['optimizer'] == 'sgd':
        return torch.optim.SGD(model.parameters(), lr=config['lr'], momentum=0.9, weight_decay=1e-4)
    return torch.optim.Adam(model.parameters(), lr=config['lr'], betas=(0.9, 0.999), eps=1e-8, weight_decay=1e-4)


def loader_new(dataset, batch, workers, seed, shuffle):
    generator = torch.Generator().manual_seed(seed)
    return DataLoader(dataset, batch_size=batch, shuffle=shuffle, num_workers=workers,
                      worker_init_fn=seed_worker, generator=generator, pin_memory=True,
                      persistent_workers=False)


def evaluate(model, loader, device):
    model.eval()
    total, correct, loss = 0, 0, 0.
    predictions, targets = [], []
    with torch.inference_mode():
        for x, y in loader:
            x, y = x.to(device), y.to(device)
            z = model(x)
            loss += nn.functional.cross_entropy(z, y, reduction='sum').item()
            pred = z.argmax(1)
            correct += (pred == y).sum().item()
            total += len(y)
            predictions.extend(pred.cpu().tolist())
            targets.extend(y.cpu().tolist())
    return {'loss': loss / total, 'accuracy': correct / total, 'count': total}, predictions, targets


def save_checkpoint(path, model, optimizer, epoch, history, best):
    state = dict(model=model.state_dict(), optimizer=optimizer.state_dict(), epoch=epoch,
                 history=history, best=best, python_rng=random.getstate(), numpy_rng=np.random.get_state(),
                 torch_rng=torch.get_rng_state(), cuda_rng=torch.cuda.get_rng_state_all())
    tmp = path.with_suffix('.tmp')
    torch.save(state, tmp)
    tmp.replace(path)


def load_checkpoint(path, model, optimizer=None):
    # These checkpoints are generated by this script, never downloaded from third parties.
    state = torch.load(path, map_location='cpu', weights_only=False)
    model.load_state_dict(state['model'])
    if optimizer is not None:
        optimizer.load_state_dict(state['optimizer'])
        random.setstate(state['python_rng'])
        np.random.set_state(state['numpy_rng'])
        torch.set_rng_state(state['torch_rng'])
        torch.cuda.set_rng_state_all(state['cuda_rng'])
    return state


def run_one(config, common, trainset, testset, out, device):
    folder = out / config['id']
    folder.mkdir(exist_ok=True)
    effective = {**common, **config, 'training_count': len(trainset), 'test_count': len(testset)}
    cp = folder / 'config.json'
    if cp.exists() and json.loads(cp.read_text(encoding='utf-8')) != effective:
        raise RuntimeError('Refusing to resume with changed configuration: ' + str(folder))
    write_json(cp, effective)
    seed_all(common['seed'])
    model = model_new(device)
    optimizer = optimizer_new(model, config)
    history, best, start = [], -1., 1
    last = folder / 'last.pt'
    if last.exists():
        state = load_checkpoint(last, model, optimizer)
        history, best, start = state['history'], state['best'], state['epoch'] + 1
    for epoch in range(start, common['epochs'] + 1):
        # Epoch-specific seeds make data augmentation and ordering restartable on Windows spawn.
        seed_all(common['seed'] + epoch)
        train_loader = loader_new(trainset, common['batch_size'], common['workers'], common['seed'] + epoch, True)
        test_loader = loader_new(testset, common['batch_size'], common['workers'], common['seed'], False)
        lr = lr_at(config, epoch)
        for group in optimizer.param_groups:
            group['lr'] = lr
        torch.cuda.synchronize()
        t0 = time.perf_counter()
        model.train()
        total, loss_sum, correct = 0, 0., 0
        for x, y in train_loader:
            x, y = x.to(device, non_blocking=True), y.to(device, non_blocking=True)
            optimizer.zero_grad(set_to_none=True)
            z = model(x)
            loss = nn.functional.cross_entropy(z, y)
            if not torch.isfinite(loss):
                write_json(folder / 'failure.json', {'epoch': epoch, 'reason': 'nonfinite_loss'})
                raise FloatingPointError(config['id'])
            loss.backward()
            optimizer.step()
            total += len(y)
            loss_sum += loss.item() * len(y)
            correct += (z.argmax(1) == y).sum().item()
        torch.cuda.synchronize()
        train_seconds = time.perf_counter() - t0
        test, predictions, targets = evaluate(model, test_loader, device)
        torch.cuda.synchronize()
        row = dict(epoch=epoch, lr=lr, train_loss=loss_sum / total, train_accuracy=correct / total,
                   test=test, train_seconds=train_seconds, epoch_seconds=time.perf_counter() - t0)
        history.append(row)
        improved = test['accuracy'] > best
        if improved:
            best = test['accuracy']
        # Commit the selected checkpoint before last, so an interruption cannot leave
        # last recording a new best that was never saved. Both writes are atomic.
        if improved:
            save_checkpoint(folder / 'best.pt', model, optimizer, epoch, history, best)
            write_json(folder / 'best_test.json', {'epoch': epoch, 'metrics': test,
                       'checkpoint': 'best.pt', 'predictions': predictions, 'targets': targets})
        save_checkpoint(last, model, optimizer, epoch, history, best)
        write_json(folder / 'last_test.json', {'epoch': epoch, 'metrics': test,
                   'checkpoint': 'last.pt', 'predictions': predictions, 'targets': targets})
        write_json(folder / 'history.json', history)
        print(json.dumps({'run': config['id'], **row}), flush=True)
        write_json(out / 'status.json', {'run': config['id'], 'epoch': epoch, 'epochs': common['epochs'], 'state': 'training'})
    state = load_checkpoint(last, model)
    write_json(folder / 'history.json', state['history'])
    return state['history']


def preflight(common, trainset, out, device):
    assert [lr_at({'lr': .1, 'milestones': [30, 40]}, e) for e in [1,30,31,40,41,50]] == [.1,.1,.010000000000000002,.010000000000000002,.0010000000000000002,.0010000000000000002]
    import tempfile
    checks = []
    for batch in [256, 128, 64]:
        seed_all(common['seed'])
        try:
            model = model_new(device)
            optimizer = optimizer_new(model, {'optimizer': 'adam', 'lr': .001})
            dl = loader_new(Subset(trainset, list(range(batch * 3))), batch, common['workers'], common['seed'], True)
            torch.cuda.reset_peak_memory_stats()
            start = time.perf_counter()
            before = next(model.parameters()).detach().clone()
            for x, y in dl:
                optimizer.zero_grad(set_to_none=True)
                z = model(x.to(device))
                assert z.shape == (batch, 100)
                nn.functional.cross_entropy(z, y.to(device)).backward()
                optimizer.step()
            torch.cuda.synchronize()
            assert not torch.equal(before, next(model.parameters()))
            with tempfile.TemporaryDirectory(prefix='exp4-check-') as temp:
                path = Path(temp) / 'resume.pt'
                save_checkpoint(path, model, optimizer, 1, [], -1.)
                model.eval()
                x = x.to(device)
                with torch.no_grad():
                    expected = model(x).clone()
                load_checkpoint(path, model, optimizer)
                with torch.no_grad():
                    assert torch.equal(expected, model(x))
                def next_step():
                    model.train()
                    optimizer.zero_grad(set_to_none=True)
                    loss = nn.functional.cross_entropy(model(x), y.to(device))
                    loss.backward()
                    optimizer.step()
                    return {k:v.detach().clone() for k,v in model.state_dict().items()}
                expected_state = next_step()
                load_checkpoint(path, model, optimizer)
                resumed_state = next_step()
                assert all(torch.equal(expected_state[k], resumed_state[k]) for k in expected_state)
            checks.append({'batch_size': batch, 'seconds_three_batches_with_checkpoint': time.perf_counter()-start,
                           'peak_allocated_bytes': torch.cuda.max_memory_allocated(), 'passed': True})
            common['batch_size'] = batch
            break
        except torch.cuda.OutOfMemoryError:
            checks.append({'batch_size': batch, 'passed': False, 'reason': 'CUDA OOM'})
            del model, optimizer
            torch.cuda.empty_cache()
    else:
        raise RuntimeError('No approved batch size fits')
    write_json(out / 'preflight.json', checks)
    return common


def main():
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument('--config', type=Path, default=BASE / 'stage1.json')
    parser.add_argument('--data', type=Path, default=BASE / 'cv_homework2/data')
    parser.add_argument('--output', type=Path, default=BASE / 'outputs/stage1_20261029_train_test')
    parser.add_argument('--preflight-only', action='store_true')
    args = parser.parse_args()
    assert torch.cuda.is_available(), 'CUDA required for approved timing comparison'
    torch.set_num_threads(4)
    torch.backends.cudnn.benchmark = False
    torch.backends.cudnn.deterministic = True
    torch.backends.cuda.matmul.allow_tf32 = False
    torch.backends.cudnn.allow_tf32 = False
    device = torch.device('cuda:0')
    args.output.mkdir(parents=True, exist_ok=True)
    # Keep a process-wide exclusive lock; Windows scheduled tasks may be restarted manually.
    lock = open(args.output / 'run.lock', 'a+b')
    if platform.system() == 'Windows':
        import msvcrt
        if lock.tell() == 0:
            lock.write(b'0')
            lock.flush()
        lock.seek(0)
        msvcrt.locking(lock.fileno(), msvcrt.LK_NBLCK, 1)
    else:
        import fcntl
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
    config = json.loads(args.config.read_text(encoding='utf-8'))
    common = dict(config['common'])
    train_tf = transforms.Compose([transforms.RandomHorizontalFlip(), transforms.RandomCrop(32, padding=4), transforms.ToTensor(), transforms.Normalize((.5,)*3,(.5,)*3)])
    eval_tf = transforms.Compose([transforms.ToTensor(), transforms.Normalize((.5,)*3,(.5,)*3)])
    trainset = torchvision.datasets.CIFAR100(str(args.data), train=True, transform=train_tf)
    testset = torchvision.datasets.CIFAR100(str(args.data), train=False, transform=eval_tf)
    assert len(trainset) == 50000 and len(testset) == 10000
    assert np.bincount(trainset.targets, minlength=100).tolist() == [500] * 100
    assert np.bincount(testset.targets, minlength=100).tolist() == [100] * 100
    if not (args.output / 'protocol.json').exists():
        common = preflight(common, trainset, args.output, device)
        version = subprocess.check_output(['git','rev-parse','HEAD'], cwd=BASE, text=True).strip()
        protocol = {'config': config, 'common': common, 'git_commit': version,
                    'data_protocol': {'train': 'official full training split', 'training_count': 50000, 'test_count': 10000, 'validation_count': 0, 'evaluation': 'test after every epoch'},
                    'source_sha256': sha(__file__), 'model_sha256': sha(BASE / 'cv_homework2/resnet-cifar100.py'),
                    'environment': {'python':platform.python_version(), 'torch':torch.__version__, 'torchvision':torchvision.__version__, 'numpy':np.__version__, 'gpu':torch.cuda.get_device_name()},
                    'data_sha256': {p.name:sha(p) for p in sorted((args.data/'cifar-100-python').iterdir()) if p.is_file()}}
        write_json(args.output / 'protocol.json', protocol)
    else:
        protocol = json.loads((args.output / 'protocol.json').read_text(encoding='utf-8'))
        if protocol['source_sha256'] != sha(__file__) or protocol['config'] != config:
            raise RuntimeError('Source or protocol changed; use a new output directory')
        common = protocol['common']
    if args.preflight_only:
        print(json.dumps({'preflight':'passed','common':common}), flush=True)
        return
    completed, failed = [], []
    for run in config['runs']:
        try:
            run_one(run, common, trainset, testset, args.output, device)
            completed.append(run['id'])
        except FloatingPointError:
            failed.append(run['id'])
    write_json(args.output/'status.json', {'state': 'incomplete' if failed else 'complete',
               'completed_runs': completed, 'failed_runs': failed})
    if failed:
        raise RuntimeError('Nonfinite loss in: ' + ', '.join(failed))
    print('STAGE1_COMPLETE', flush=True)


if __name__ == '__main__':
    main()
